import { build } from 'esbuild';
import { readFile, mkdir, writeFile } from 'node:fs/promises';

const bundle = await build({
  entryPoints: ['src/browser.ts'], bundle: true, write: false, minify: true,
  format: 'iife', target: ['es2022'], legalComments: 'none'
});
const css = await readFile('src/reader.css', 'utf8');
const { version } = JSON.parse(await readFile('package.json', 'utf8'));
const script = bundle.outputFiles[0].text;
if (/<\/script/i.test(script) || /<\/style/i.test(css)) throw new Error('Unsafe inline asset delimiter');
await mkdir('src/generated', { recursive: true });
await writeFile('src/generated/assets.ts',
  `// Generated by scripts/build.mjs.\nexport const script = ${JSON.stringify(script)};\n` +
  `export const css = ${JSON.stringify(css)};\nexport const version = ${JSON.stringify(version)};\n`);
